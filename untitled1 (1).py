# AI Lab Task: Minimax and Alpha-Beta Pruning

scores = [3, 5, 2, 9, 3, 5, 2, 9]

minimax_count = 0
alpha_beta_count = 0


# Task 1 and Task 2: Minimax with leaf counter
def minimax(depth, index, maximizing, scores, max_depth):
    global minimax_count

    if depth == max_depth:
        minimax_count += 1
        return scores[index]

    if maximizing:
        value = float('-inf')

        for i in range(2):
            result = minimax(
                depth + 1,
                index * 2 + i,
                False,
                scores,
                max_depth
            )
            value = max(value, result)

        return value

    else:
        value = float('inf')

        for i in range(2):
            result = minimax(
                depth + 1,
                index * 2 + i,
                True,
                scores,
                max_depth
            )
            value = min(value, result)

        return value


# Task 2: Alpha-Beta Pruning with leaf counter
def alpha_beta(depth, index, maximizing, scores,
               max_depth, alpha, beta):
    global alpha_beta_count

    if depth == max_depth:
        alpha_beta_count += 1
        return scores[index]

    if maximizing:
        value = float('-inf')

        for i in range(2):
            result = alpha_beta(
                depth + 1,
                index * 2 + i,
                False,
                scores,
                max_depth,
                alpha,
                beta
            )

            value = max(value, result)
            alpha = max(alpha, value)

            if alpha >= beta:
                break

        return value

    else:
        value = float('inf')

        for i in range(2):
            result = alpha_beta(
                depth + 1,
                index * 2 + i,
                True,
                scores,
                max_depth,
                alpha,
                beta
            )

            value = min(value, result)
            beta = min(beta, value)

            if alpha >= beta:
                break

        return value


# Run both algorithms
depth = 3

minimax_value = minimax(0, 0, True, scores, depth)

alpha_beta_value = alpha_beta(
    0, 0, True, scores, depth,
    float('-inf'), float('inf')
)

print("TASK 1: MINIMAX")
print("Minimax root value:", minimax_value)

print("\nTASK 2: LEAF COUNTER")
print("Alpha-Beta root value:", alpha_beta_value)
print("Minimax leaves evaluated:", minimax_count)
print("Alpha-Beta leaves evaluated:", alpha_beta_count)

print("\nTASK 3: REORDER BRANCHES")

reordered_scores = [9, 3, 5, 2, 9, 3, 5, 2]

minimax_count = 0
alpha_beta_count = 0

minimax_value = minimax(
    0, 0, True, reordered_scores, depth
)

alpha_beta_value = alpha_beta(
    0, 0, True, reordered_scores, depth,
    float('-inf'), float('inf')
)

print("Minimax root value:", minimax_value)
print("Alpha-Beta root value:", alpha_beta_value)
print("Minimax leaves evaluated:", minimax_count)
print("Alpha-Beta leaves evaluated:", alpha_beta_count)